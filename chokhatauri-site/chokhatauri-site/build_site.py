def img(file, alt, cat, where="", eager=False, fb=()):
    IMAGES.setdefault(file, (alt, where))
    chain = []
    for f in list(fb) + DEFAULT_FB.get(file, []):
        chain += ["assets/img/" + f] + ([REMOTE[f]] if f in REMOTE else [])
    chain += ["assets/img/" + f for f in CAT_FB.get(cat, [])]
    rem = "|".join(([REMOTE[file]] if file in REMOTE else []) + chain)
    load = "" if eager else ' loading="lazy"'
    return ('<img src="assets/img/%s" data-file="%s" data-cat="%s" data-remote="%s" alt="%s"%s decoding="async">'
            % (file, file, cat, rem, E(alt, quote=True), load))


